// Attachment is a file attached to a message. In JSON, Content is a
// standard base64 string.
type Attachment struct {
	Filename    string `json:"filename"`
	ContentType string `json:"content_type,omitempty"`
	Content     []byte `json:"content"`
}

// Message is a single email ready to be rendered to RFC 5322 bytes.
type Message struct {
	From        Address
	To          []Address
	Cc          []Address
	Bcc         []Address
	ReplyTo     *Address
	Subject     string
	Text        string
	HTML        string
	Headers     map[string]string
	Attachments []Attachment
}

// reservedHeaders are generated by the builder and may not be overridden
// through Message.Headers.
var reservedHeaders = map[string]bool{
	"From": true, "To": true, "Cc": true, "Bcc": true, "Reply-To": true,
	"Subject": true, "Date": true, "Message-Id": true, "Mime-Version": true,
	"Content-Type": true, "Content-Transfer-Encoding": true, "Sender": true,
}

// MaxSubjectLength keeps the Subject header comfortably below the
// 998-character line limit of RFC 5322.
const MaxSubjectLength = 900

// Validate checks the message for missing fields and header injection.
func (m *Message) Validate() error {
	if err := m.From.Validate(); err != nil {
		return fmt.Errorf("from: %w", err)
	}
	if len(m.To)+len(m.Cc)+len(m.Bcc) == 0 {
		return errors.New("at least one recipient (to, cc or bcc) is required")
	}
	for field, list := range map[string][]Address{"to": m.To, "cc": m.Cc, "bcc": m.Bcc} {
		for i, a := range list {
			if err := a.Validate(); err != nil {
				return fmt.Errorf("%s[%d]: %w", field, i, err)
			}
		}
	}
	if m.ReplyTo != nil {
		if err := m.ReplyTo.Validate(); err != nil {
			return fmt.Errorf("reply_to: %w", err)
		}
	}
	if strings.TrimSpace(m.Subject) == "" {
		return errors.New("subject is required")
	}
	if strings.ContainsAny(m.Subject, "\r\n") {
		return errors.New("subject must not contain line breaks")
	}
	if len(m.Subject) > MaxSubjectLength {
		return fmt.Errorf("subject must be at most %d bytes", MaxSubjectLength)
	}
	if m.Text == "" && m.HTML == "" {
		return errors.New("text or html body is required")
	}
	for k, v := range m.Headers {
		if err := validateHeader(k, v); err != nil {
			return err
		}
	}
	for i, a := range m.Attachments {
		if err := a.validate(); err != nil {
			return fmt.Errorf("attachments[%d]: %w", i, err)
		}
	}
	return nil
}

func validateHeader(name, value string) error {
	if name == "" {
		return errors.New("header name must not be empty")
	}
	for _, r := range name {
		if r <= ' ' || r > '~' || r == ':' {
			return fmt.Errorf("invalid header name %q", name)
		}
	}
	if reservedHeaders[textproto.CanonicalMIMEHeaderKey(name)] {
		return fmt.Errorf("header %q is managed by mailcore and cannot be set", name)
	}
	if strings.ContainsAny(value, "\r\n") {
		return fmt.Errorf("header %q must not contain line breaks", name)
	}
	return nil
}

func (a Attachment) validate() error {
	if a.Filename == "" || strings.ContainsAny(a.Filename, "\r\n\x00") {
		return errors.New("filename is required and must be a single line")
	}
	if len(a.Content) == 0 {
		return errors.New("content is empty")
	}
	if a.ContentType != "" {
		if _, _, err := mime.ParseMediaType(a.ContentType); err != nil {
			return fmt.Errorf("invalid content_type %q", a.ContentType)
		}
	}
	return nil
}

// Recipients returns the de-duplicated envelope recipients (to, cc, bcc).
func (m *Message) Recipients() []string {
	seen := make(map[string]bool)
	var out []string
	for _, list := range [][]Address{m.To, m.Cc, m.Bcc} {
		for _, a := range list {
			key := strings.ToLower(a.Email)
			if !seen[key] {
				seen[key] = true
				out = append(out, a.Email)
			}
		}
	}
	return out
}

// NewMessageID returns a globally unique Message-ID for the given domain.
func NewMessageID(domain string) string {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		panic(err)
	}
	return fmt.Sprintf("<%s@%s>", hex.EncodeToString(b), domain)
}

// Build renders the message to RFC 5322 bytes with CRLF line endings.
// Bcc recipients are deliberately not written to the headers.
func (m *Message) Build(date time.Time, messageID string) ([]byte, error) {
	var buf bytes.Buffer
	writeHeader(&buf, "From", m.From.String())
	if len(m.To) > 0 {
		writeHeader(&buf, "To", joinAddresses(m.To))
	}
	if len(m.Cc) > 0 {
		writeHeader(&buf, "Cc", joinAddresses(m.Cc))
	}
	if m.ReplyTo != nil {
		writeHeader(&buf, "Reply-To", m.ReplyTo.String())
	}
	writeHeader(&buf, "Subject", mime.QEncoding.Encode("utf-8", m.Subject))
	writeHeader(&buf, "Date", date.Format(time.RFC1123Z))
	writeHeader(&buf, "Message-ID", messageID)
	keys := make([]string, 0, len(m.Headers))
	for k := range m.Headers {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		writeHeader(&buf, textproto.CanonicalMIMEHeaderKey(k), m.Headers[k])
	}
	writeHeader(&buf, "MIME-Version", "1.0")

	contentHeader, contentBody, err := m.contentEntity()
	if err != nil {
		return nil, err
	}
	if len(m.Attachments) == 0 {
		writeMIMEHeader(&buf, contentHeader)
		buf.WriteString("\r\n")
		buf.Write(contentBody)
		return buf.Bytes(), nil
	}

	var body bytes.Buffer
	mw := multipart.NewWriter(&body)
	p, err := mw.CreatePart(contentHeader)
	if err != nil {
		return nil, err
	}
	if _, err := p.Write(contentBody); err != nil {
		return nil, err
	}
	for _, a := range m.Attachments {
		if err := writeAttachment(mw, a); err != nil {
			return nil, err
		}
	}
	if err := mw.Close(); err != nil {
		return nil, err
	}
	writeHeader(&buf, "Content-Type", `multipart/mixed; boundary="`+mw.Boundary()+`"`)
	buf.WriteString("\r\n")
	buf.Write(body.Bytes())
	return buf.Bytes(), nil
}

// contentEntity returns the text and/or HTML body as a MIME entity.
func (m *Message) contentEntity() (textproto.MIMEHeader, []byte, error) {
	switch {
	case m.Text != "" && m.HTML != "":
		var b bytes.Buffer
		mw := multipart.NewWriter(&b)
		for _, part := range []struct{ ct, body string }{{"text/plain", m.Text}, {"text/html", m.HTML}} {
			h, body := textEntity(part.ct, part.body)
			w, err := mw.CreatePart(h)
			if err != nil {
				return nil, nil, err
			}
			if _, err := w.Write(body); err != nil {
				return nil, nil, err
			}
		}
		if err := mw.Close(); err != nil {
			return nil, nil, err
		}
		h := textproto.MIMEHeader{}
		h.Set("Content-Type", `multipart/alternative; boundary="`+mw.Boundary()+`"`)
		return h, b.Bytes(), nil
	case m.HTML != "":
		h, body := textEntity("text/html", m.HTML)
		return h, body, nil
	default:
		h, body := textEntity("text/plain", m.Text)
		return h, body, nil
	}
}

// textEntity encodes s as quoted-printable UTF-8.
func textEntity(contentType, s string) (textproto.MIMEHeader, []byte) {
	h := textproto.MIMEHeader{}
	h.Set("Content-Type", contentType+"; charset=UTF-8")
	h.Set("Content-Transfer-Encoding", "quoted-printable")
	var b bytes.Buffer
	qw := quotedprintable.NewWriter(&b)
	// Writes to a bytes.Buffer cannot fail.
	_, _ = qw.Write([]byte(s))
	_ = qw.Close()
	return h, b.Bytes()
}

func writeAttachment(mw *multipart.Writer, a Attachment) error {
	name := path.Base(strings.ReplaceAll(a.Filename, `\`, "/"))
	ct := a.ContentType
	if ct == "" {
		ct = mime.TypeByExtension(path.Ext(name))
	}
	if ct == "" {
		ct = "application/octet-stream"
	}
	mediaType, params, err := mime.ParseMediaType(ct)
	if err != nil {
		return fmt.Errorf("attachment %q: invalid content type", name)
	}
	params["name"] = name
	h := textproto.MIMEHeader{}
	h.Set("Content-Type", mime.FormatMediaType(mediaType, params))
	h.Set("Content-Disposition", mime.FormatMediaType("attachment", map[string]string{"filename": name}))
	h.Set("Content-Transfer-Encoding", "base64")
	w, err := mw.CreatePart(h)
	if err != nil {
		return err
	}
	encoded := base64.StdEncoding.EncodeToString(a.Content)
	for len(encoded) > 76 {
		if _, err := w.Write([]byte(encoded[:76] + "\r\n")); err != nil {
			return err
		}
		encoded = encoded[76:]
	}
	_, err = w.Write([]byte(encoded + "\r\n"))
	return err
}

func joinAddresses(list []Address) string {
	parts := make([]string, len(list))
	for i, a := range list {
		parts[i] = a.String()
	}
	// Fold after each address so long recipient lists stay within line limits.
	return strings.Join(parts, ",\r\n ")
}

func writeHeader(buf *bytes.Buffer, name, value string) {
	buf.WriteString(name)
	buf.WriteString(": ")
	buf.WriteString(value)
	buf.WriteString("\r\n")
}

func writeMIMEHeader(buf *bytes.Buffer, h textproto.MIMEHeader) {
	keys := make([]string, 0, len(h))
	for k := range h {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		for _, v := range h[k] {
			writeHeader(buf, k, v)
		}
	}
}
